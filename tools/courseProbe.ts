type V3 = [number, number, number]
interface Aabb { min: V3; max: V3 }
type Obj = Record<string, unknown>

export function loadAuthoredCourse(id: string): Promise<CourseV1> {
  return loadCourseV1File(`courses/${id}.course.json`)
}

// buildContent regenerates every placeholder: once per process is enough.
let generated: Promise<Map<string, string>> | undefined

export async function generatedCourse(id: string): Promise<CourseV1> {
  if (!generated) generated = buildContent({ files: [] })
  const rel = `courses/${id}.course.json`
  const text = (await generated).get(rel)
  if (text === undefined) refuse('course', rel, 'not generated by tools/placeholders.ts; use a generated course id')
  return loadCourseV1(JSON.parse(text), rel, nodeGameAssets())
}

// Asset bounds are sim Vec3 objects; the probe works on arrays.
const aabbOf = (b: { min: Vec3; max: Vec3 }): Aabb => ({ min: [b.min.x, b.min.y, b.min.z], max: [b.max.x, b.max.y, b.max.z] })

const VIEW_KEYS = ['decor', 'environment']

export function simDiff(a: CourseV1, b: CourseV1, ignore: readonly string[]): string[] {
  const out: string[] = []
  const keys = [...new Set([...Object.keys(a.json), ...Object.keys(b.json)])].sort()
  const show = (v: unknown) => JSON.stringify(v)
  for (const k of keys) {
    if (VIEW_KEYS.includes(k) || ignore.includes(k)) continue
    const va = a.json[k]
    const vb = b.json[k]
    if (k === 'obstacles' && Array.isArray(va) && Array.isArray(vb)) {
      if (va.length !== vb.length) out.push(`obstacles/length: ${va.length} != ${vb.length}`)
      for (let i = 0; i < Math.min(va.length, vb.length); i++) {
        if (!isDeepStrictEqual(va[i], vb[i])) out.push(`obstacles/${i}: ${show(va[i])} != ${show(vb[i])}`)
      }
    } else if (!isDeepStrictEqual(va, vb)) {
      out.push(`${k}: ${show(va)} != ${show(vb)}`)
    }
  }
  return out
}

const rotate = (q: readonly number[], v: V3): V3 => {
  const [x, y, z, w] = q
  const tx = 2 * (y * v[2] - z * v[1])
  const ty = 2 * (z * v[0] - x * v[2])
  const tz = 2 * (x * v[1] - y * v[0])
  return [v[0] + w * tx + (y * tz - z * ty), v[1] + w * ty + (z * tx - x * tz), v[2] + w * tz + (x * ty - y * tx)]
}

function placed(b: Aabb, t: readonly number[], r: readonly number[], s: readonly number[]): Aabb {
  const min: V3 = [Infinity, Infinity, Infinity]
  const max: V3 = [-Infinity, -Infinity, -Infinity]
  for (let i = 0; i < 8; i++) {
    const c: V3 = [(i & 1 ? b.max : b.min)[0] * s[0], (i & 2 ? b.max : b.min)[1] * s[1], (i & 4 ? b.max : b.min)[2] * s[2]]
    const p = rotate(r, c)
    for (let k = 0; k < 3; k++) {
      min[k] = Math.min(min[k], p[k] + t[k])
      max[k] = Math.max(max[k], p[k] + t[k])
    }
  }
  return { min, max }
}

const box = (center: number[], half: number[]): Aabb => ({
  min: [center[0] - half[0], center[1] - half[1], center[2] - half[2]],
  max: [center[0] + half[0], center[1] + half[1], center[2] + half[2]],
})
const hits = (a: Aabb, b: Aabb) => a.min.every((v, k) => v < b.max[k] && a.max[k] > b.min[k])

const MINIMUMS: Readonly<Record<string, Readonly<Record<string, number>>>> = {
  race: { 'candy.banner': 2, 'candy.hot-air-balloon': 1, 'candy.tower': 3, 'candy.cloud': 4, 'candy.slime-pool': 1 },
  survival: { 'candy.banner': 2, 'candy.hot-air-balloon': 1, 'candy.tower': 3, 'candy.cloud': 4, 'candy.slime-pool': 1 },
  hub: { 'candy.banner': 4, 'candy.tower': 2, 'candy.cloud': 3, 'candy.hot-air-balloon': 1 },
  podium: { 'candy.banner': 2, 'candy.cloud': 2 },
}
const DECOR_CAP = 48
const FLOORS = ['candy.floor-tile', 'candy.floor-disc']

export async function decorProblems(c: CourseV1, assets: GameAssetResolver): Promise<string[]> {
  const out: string[] = []
  const decor = c.decor
  if (decor.length > DECOR_CAP) out.push(`${decor.length} decor items, over the cap of ${DECOR_CAP}`)
  const counts = new Map<string, number>()
  for (const d of decor) counts.set(d.asset, (counts.get(d.asset) ?? 0) + 1)
  for (const [asset, n] of Object.entries(MINIMUMS[c.kind] ?? {})) {
    const have = counts.get(asset) ?? 0
    if (have < n) out.push(`missing decor: ${have} ${asset}, at least ${n} needed`)
  }
  const bounds = async (id: string): Promise<Aabb | string> => {
    try {
      return aabbOf((await assets.resolve(id)).asset.bounds)
    } catch (e) {
      return (e as Error).message
    }
  }
  // Out-of-play boxes: placed obstacles, spawns, checkpoints, finish, queue pad.
  const j = c.json
  const play: { name: string; b: Aabb }[] = []
  let floorTop = Infinity
  const obstacles = (j.obstacles ?? []) as Obj[]
  for (const o of obstacles) {
    const b = await bounds(o.asset as string)
    if (typeof b === 'string') { out.push(`obstacle ${o.id}: ${b}`); continue }
    const p = placed(b, o.t as number[], o.r as number[], o.s as number[])
    play.push({ name: `obstacle ${o.id}`, b: p })
    if (FLOORS.includes(o.asset as string)) floorTop = Math.min(floorTop, p.max[1])
  }
  ((j.spawns ?? []) as Obj[]).forEach((s, i) => play.push({ name: `spawn ${i}`, b: box(s.t as number[], [0.4, 0.85, 0.4]) }))
  ;((j.checkpoints ?? []) as Obj[]).forEach((k, i) => play.push({ name: `checkpoint ${i}`, b: box(k.center as number[], k.half as number[]) }))
  for (const key of ['finish', 'queuePad']) {
    const z = j[key] as Obj | null | undefined
    if (z) play.push({ name: key, b: box(z.center as number[], z.half as number[]) })
  }
  const killY = j.killPlaneY as number
  for (const d of decor) {
    if (!/^d-[0-9]+$/.test(d.id)) out.push(`decor id '${d.id}' does not match ^d-[0-9]+$`)
    let r
    try {
      r = await assets.resolve(d.asset)
    } catch (e) {
      out.push(`decor ${d.id}: ${(e as Error).message}`)
      continue
    }
    if (r.asset.world !== 'candy' || r.asset.category !== 'scenery') {
      out.push(`decor ${d.id}: asset ${d.asset} is ${r.asset.world}/${r.asset.category}, not candy/scenery`)
    }
    const p = placed(aabbOf(r.asset.bounds), d.t, d.r, d.s)
    if (d.asset === 'candy.slime-pool' && !(p.min[1] > killY && p.max[1] < floorTop)) {
      out.push(`decor ${d.id}: slime pool y ${p.min[1]}..${p.max[1]} is not between killPlaneY ${killY} and the lowest floor top ${floorTop}`)
    }
    for (const q of play) if (hits(p, q.b)) out.push(`decor ${d.id} (${d.asset}) intersects ${q.name}`)
  }
  return out
}

export async function playSprint(R: RapierModule, chosen: string, other: string, seed: number): Promise<{ done: boolean; winner: number; finalHash: string; ownRoundQualified: number }> {
  const courses = []
  for (const id of [chosen, other]) {
    const c = await loadAuthoredCourse(id)
    if (!c.sim) refuse('course', `courses/${id}.course.json`, 'has no sim; pick a race or survival course')
    courses.push(c.sim)
  }
  courses.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0)
  const setup: MatchSetup = { seed, playerCount: 8, humans: new Array<boolean>(8).fill(false), profile: 'sprint', courses }
  const { log } = runMatchOffline(R, setup)
  let own = Infinity
  for (const r of log.rounds) if (r.course === chosen) own = Math.min(own, r.qualified.length)
  return {
    done: log.winner >= 0,
    winner: log.winner,
    finalHash: log.finalHash,
    ownRoundQualified: own === Infinity ? 0 : own,
  }
}
